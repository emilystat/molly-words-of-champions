echo "=============================================="
echo ""
echo "Step 1: Create the GitHub Repository"
echo "-------------------------------------"
echo ""
echo "In the browser window that opened:"
echo ""
echo "  Repository name: molly-words-of-champions"
echo "  Description: Words of Champions spelling bee practice website"
