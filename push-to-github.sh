    echo "❌ Push failed. Common issues:"
    echo ""
    echo "1. Repository not created yet - go back and create it"
    echo "2. Authentication needed - you may need to enter your GitHub username/password"
    echo "   (Note: GitHub requires a Personal Access Token instead of password)"
    echo ""
    echo "To try again, run: bash push-to-github.sh"
